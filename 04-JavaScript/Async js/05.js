/**
 * Q5. List and briefly explain some common Browser APIs available to JavaScript developers.
    DOM API (Document Object Model): Allows JavaScript to interact with and manipulate HTML and XML documents. You can access and modify the structure, style, and content of web pages.

    Fetch API: Provides a modern interface for making network requests (like XMLHttpRequest) but with promises. It simplifies making AJAX requests.

    Geolocation API: Enables web applications to access the geographical location of a user's device, if permission is granted.

    Canvas API: Allows for drawing graphics and animations on a web page using JavaScript. It is commonly used in games and visual data representations.

    Web Storage API (localStorage and sessionStorage): Allows the storing of data in the browser. localStorage persists across sessions, while sessionStorage lasts until the page is closed.

    WebSockets API: Allows for full-duplex communication channels over a single TCP connection, enabling real-time communication between a browser and server.
 */